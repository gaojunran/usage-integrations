describe("positional arguments", () => {
  it("converts required positional args", () => {
    const y = createYargs()
      .scriptName("cmd")
      .command("add <file>", "Add a file", () => {});

    const spec = convertRoot(y);
    const addCmd = spec.cmds.find((c) => c.name === "add");
    expect(addCmd).toBeDefined();
    expect(addCmd!.args).toHaveLength(1);
    expect(addCmd!.args[0].name).toBe("file");
    expect(addCmd!.args[0].required).toBe(true);
  });

  it("converts optional positional args", () => {
    const y = createYargs()
      .scriptName("cmd")
      .command("list [filter]", "List items", () => {});

    const spec = convertRoot(y);
    const listCmd = spec.cmds.find((c) => c.name === "list");
    expect(listCmd).toBeDefined();
    expect(listCmd!.args).toHaveLength(1);
    expect(listCmd!.args[0].name).toBe("filter");
    expect(listCmd!.args[0].required).toBe(false);
  });

  it("converts variadic positional args", () => {
    const y = createYargs()
      .scriptName("cmd")
      .command("add <files..>", "Add files", () => {});

    const spec = convertRoot(y);
    const addCmd = spec.cmds.find((c) => c.name === "add");
    expect(addCmd).toBeDefined();
    expect(addCmd!.args).toHaveLength(1);
    expect(addCmd!.args[0].name).toBe("files");
    expect(addCmd!.args[0].var).toBe(true);
  });

  it("converts mixed required and optional args", () => {
    const y = createYargs()
      .scriptName("cmd")
      .command("copy <source> [dest]", "Copy files", () => {});

    const spec = convertRoot(y);
    const copyCmd = spec.cmds.find((c) => c.name === "copy");
    expect(copyCmd).toBeDefined();
    expect(copyCmd!.args).toHaveLength(2);
    expect(copyCmd!.args[0].name).toBe("source");
    expect(copyCmd!.args[0].required).toBe(true);
    expect(copyCmd!.args[1].name).toBe("dest");
    expect(copyCmd!.args[1].required).toBe(false);
  });
});

