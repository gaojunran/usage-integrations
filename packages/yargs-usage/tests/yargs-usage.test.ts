import { describe, it, expect } from "vitest";
import yargs from "yargs";
import { generate, generateKDL, generateJSON, convertRoot } from "../src/index.js";
import { validateKDL } from "@usage-spec/core";

// Helper to create a yargs instance without calling .parse()
function createYargs(): ReturnType<typeof yargs> {
  return yargs([]).help(false).version(false);
}

describe("simple command", () => {
  it("generates spec for a basic CLI with version and options", () => {
    const y = createYargs()
      .scriptName("mycli")
      .version("1.0.0")
      .option("verbose", {
        alias: "v",
        type: "boolean",
        description: "Enable verbose output",
      })
      .option("config", {
        alias: "c",
        type: "string",
        description: "Config file path",
      });

    const output = generate(y, "mycli");

    expect(output).toContain("name mycli");
    expect(output).toContain("bin mycli");
    expect(output).toContain(`version "1.0.0"`);
    expect(output).toContain("verbose");
    expect(output).toContain("config");
  });

  it("includes generated comment header", () => {
    const y = createYargs().scriptName("app");
    const output = generate(y);
    expect(output).toContain("// @generated by @usage-spec/yargs from yargs metadata");
  });

  it("uses custom bin name when provided", () => {
    const y = createYargs().scriptName("app");
    const output = generate(y, "my-app");
    expect(output).toContain("bin my-app");
  });
});

describe("version", () => {
  it("extracts version string", () => {
    const y = createYargs().scriptName("app").version("2.0.0");
    const spec = convertRoot(y);
    expect(spec.version).toBe("2.0.0");
  });

  it("skips version field when not set", () => {
    const y = createYargs().scriptName("app");
    const output = generate(y);
    expect(output).not.toContain("version ");
  });
});

describe("about/description", () => {
  it("extracts usage description as about", () => {
    const y = createYargs().scriptName("app").usage("A simple CLI tool");
    const spec = convertRoot(y);
    expect(spec.about).toBe("A simple CLI tool");
  });
});

describe("nested subcommands", () => {
  it("renders subcommands recursively", () => {
    const y = createYargs()
      .scriptName("app")
      .usage("An app")
      .command("sub", "A subcommand", (yargs) => {
        return yargs.command("nested", "A nested command");
      });

    const output = generate(y);

    expect(output).toContain("cmd sub");
    expect(output).toContain("help=\"A subcommand\"");
    expect(output).toContain("cmd nested");
    expect(output).toContain("help=\"A nested command\"");
  });

  it("renders deeply nested command structure", () => {
    const y = createYargs()
      .scriptName("myapp")
      .version("1.0.0")
      .usage("My application")
      .command("db", "Database operations", (yargs) => {
        return yargs.command("migrate", "Run migrations", (yargs) => {
          return yargs
            .command("up", "Apply migrations")
            .command("down", "Rollback migrations");
        });
      });

    const output = generate(y);

    expect(output).toContain("cmd db");
    expect(output).toContain("help=\"Database operations\"");
    expect(output).toContain("cmd migrate");
    expect(output).toContain("help=\"Run migrations\"");
    expect(output).toContain("cmd up");
    expect(output).toContain("help=\"Apply migrations\"");
    expect(output).toContain("cmd down");
    expect(output).toContain("help=\"Rollback migrations\"");
  });
});

describe("options", () => {
  it("renders short and long flags", () => {
    const y = createYargs().option("verbose", {
      alias: "v",
      type: "boolean",
      description: "Be verbose",
    });

    const output = generate(y);

    expect(output).toContain("flag");
    expect(output).toContain("verbose");
  });

  it("marks required options", () => {
    const y = createYargs().option("env", {
      type: "string",
      description: "Target environment",
      demandOption: true,
    });

    const output = generate(y);

    expect(output).toContain("required=#true");
  });

  it("renders default values for string options", () => {
    const y = createYargs()
      .option("format", {
        type: "string",
        description: "Output format",
        default: "json",
      })
      .option("retries", {
        type: "number",
        description: "Number of retries",
        default: 3,
      });

    const spec = convertRoot(y);
    const formatFlag = spec.flags.find((f) => f.long === "format");
    expect(formatFlag).toBeDefined();
    expect(formatFlag!.default).toEqual(["json"]);

    const retriesFlag = spec.flags.find((f) => f.long === "retries");
    expect(retriesFlag).toBeDefined();
    expect(retriesFlag!.default).toEqual(["3"]);
  });

  it("renders boolean default true", () => {
    const y = createYargs().option("color", {
      type: "boolean",
      description: "Enable color",
      default: true,
    });

    const spec = convertRoot(y);
    const colorFlag = spec.flags.find((f) => f.long === "color");
    expect(colorFlag).toBeDefined();
    expect(colorFlag!.defaultBool).toBe(true);
  });

  it("skips false default for boolean flags", () => {
    const y = createYargs().option("force", {
      type: "boolean",
      description: "Force the operation",
      default: false,
    });

    const spec = convertRoot(y);
    const forceFlag = spec.flags.find((f) => f.long === "force");
    expect(forceFlag).toBeDefined();
    expect(forceFlag!.default).toEqual([]);
    expect(forceFlag!.defaultBool).toBeNull();
  });

  it("preserves string zero as default", () => {
    const y = createYargs().option("port", {
      type: "string",
      description: "Port number",
      default: "0",
    });

    const output = generate(y);
    expect(output).toContain(`default="0"`);
  });

  it("renders choices", () => {
    const y = createYargs().option("format", {
      type: "string",
      description: "Output format",
      choices: ["json", "yaml", "toml"],
    });

    const spec = convertRoot(y);
    const formatFlag = spec.flags.find((f) => f.long === "format");
    expect(formatFlag).toBeDefined();
    expect(formatFlag!.arg?.choices?.values).toEqual(["json", "yaml", "toml"]);
  });

  it("hides hidden options", () => {
    const y = createYargs().option("secret", {
      type: "string",
      description: "Secret option",
      hidden: true,
    });

    const spec = convertRoot(y);
    const secretFlag = spec.flags.find((f) => f.long === "secret");
    expect(secretFlag).toBeDefined();
    expect(secretFlag!.hide).toBe(true);
  });

  it("handles count options", () => {
    const y = createYargs().option("verbose", {
      alias: "v",
      count: true,
      description: "Verbosity level",
    });

    const spec = convertRoot(y);
    const verboseFlag = spec.flags.find((f) => f.long === "verbose");
    expect(verboseFlag).toBeDefined();
    expect(verboseFlag!.count).toBe(true);
  });

  it("handles array/multiple options", () => {
    const y = createYargs().option("include", {
      type: "string",
      array: true,
      description: "Include patterns",
    });

    const spec = convertRoot(y);
    const includeFlag = spec.flags.find((f) => f.long === "include");
    expect(includeFlag).toBeDefined();
    expect(includeFlag!.var).toBe(true);
    expect(includeFlag!.arg?.var).toBe(true);
  });
});

