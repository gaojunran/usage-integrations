describe("JSON output", () => {
  it("generates JSON output with correct structure", () => {
    const y = createYargs()
      .scriptName("mycli")
      .version("2.0.0")
      .usage("A CLI tool")
      .option("verbose", {
        alias: "v",
        type: "boolean",
        description: "Be verbose",
      })
      .command("run", "Run something", () => {});

    const json = generateJSON(y);
    const parsed = JSON.parse(json);

    expect(parsed.name).toBe("mycli");
    expect(parsed.bin).toBe("mycli");
    expect(parsed.version).toBe("2.0.0");
    expect(parsed.about).toBe("A CLI tool");
    expect(parsed.flags).toHaveLength(1);
    expect(parsed.cmds).toHaveLength(1);
    expect(parsed.cmds[0].name).toBe("run");
  });

  it("includes choices in JSON output", () => {
    const y = createYargs()
      .scriptName("deploy")
      .option("env", {
        type: "string",
        description: "Environment",
        choices: ["dev", "prod"],
      });

    const json = generateJSON(y);
    const parsed = JSON.parse(json);

    expect(parsed.flags[0].arg.choices).toEqual(["dev", "prod"]);
  });

  it("includes flag details in JSON", () => {
    const y = createYargs()
      .scriptName("app")
      .option("env", {
        type: "string",
        description: "Target environment",
        demandOption: true,
      });

    const json = generateJSON(y);
    const parsed = JSON.parse(json);

    expect(parsed.flags).toHaveLength(1);
    expect(parsed.flags[0].required).toBe(true);
    expect(parsed.flags[0].arg.name).toBe("ENV");
  });

  it("handles custom bin name in JSON", () => {
    const y = createYargs().scriptName("app").usage("A tool");
    const json = generateJSON(y, "my-tool");
    const parsed = JSON.parse(json);

    expect(parsed.bin).toBe("my-tool");
  });
});

