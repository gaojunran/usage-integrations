    test("generates spec for a basic CLI with version and options") {
        @Command(name = "mycli", description = ["A simple CLI"], version = ["1.0.0"])
        class MyCli {
            @Option(names = ["-v", "--verbose"], description = ["Enable verbose output"])
            var verbose: Boolean = false

            @Option(names = ["-c", "--config"], description = ["Config file path"], paramLabel = "PATH")
            var config: String? = null
        }

        val cmd = CommandLine(MyCli())
        val output = generate(cmd)

        output.shouldContain("name mycli")
        output.shouldContain("bin mycli")
        output.shouldContain("""version "1.0.0"""")
        output.shouldContain("""about "A simple CLI"""")
        output.shouldContain("""flag "-v --verbose" help="Enable verbose output"""")
        output.shouldContain("""flag "-c --config" help="Config file path"""")
    }

