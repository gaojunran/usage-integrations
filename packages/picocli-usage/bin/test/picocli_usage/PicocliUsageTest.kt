    test("includes flag details in JSON") {
        @Command(name = "app")
        class App {
            @Option(names = ["--env"], description = ["Target environment"], required = true, paramLabel = "ENV")
            var env: String? = null

            @Option(names = ["--color"], description = ["Disable color"], negatable = true)
            var color: Boolean = false
        }

        val cmd = CommandLine(App())
        val json = generateJSON(cmd)
        val parsed = Json.parseToJsonElement(json).jsonObject

        val flags = parsed["flags"]!!.jsonArray
        flags.size shouldBe 2

        val envFlag = flags.find { it.jsonObject["name"]!!.jsonPrimitive.content == "--env" }!!.jsonObject
        envFlag["required"]!!.jsonPrimitive.boolean shouldBe true
        val envArg = envFlag["arg"]!!.jsonObject
        envArg["name"]!!.jsonPrimitive.content shouldBe "ENV"

        val colorFlag = flags.find { it.jsonObject["name"]!!.jsonPrimitive.content == "--color" }!!.jsonObject
        colorFlag["negate"]!!.jsonPrimitive.content shouldBe "--color"
    }

