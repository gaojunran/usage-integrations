package jcommander_usage

import com.beust.jcommander.JCommander
import com.beust.jcommander.Parameter
import com.beust.jcommander.Parameters
import io.kotest.assertions.throwables.shouldNotThrowAny
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.nulls.shouldNotBeNull
import io.kotest.matchers.shouldBe
import io.kotest.matchers.shouldNotBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain
import usage_spec.validateKDL

class JCommanderUsageTest : FunSpec({

    context("simple command") {
        test("generates spec for a basic CLI with options") {
            @Parameters(commandNames = ["mycli"], commandDescription = "A simple CLI")
            class MyCli {
                @Parameter(names = ["-v", "--verbose"], description = "Enable verbose output")
                var verbose = false

                @Parameter(names = ["-c", "--config"], description = "Config file path")
                var config: String? = null
            }

            val jc = JCommander(MyCli())
            val output = generate(jc)

            output.shouldContain("name mycli")
            output.shouldContain("bin mycli")
            output.shouldContain("""flag "-v --verbose" help="Enable verbose output""")
            output.shouldContain("""flag "-c --config" help="Config file path"""")
        }

        test("includes generated comment header") {
            class App
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("// @generated by jcommander-usage from JCommander metadata")
        }

        test("uses custom bin name when provided") {
            class App
            val jc = JCommander(App())
            val output = generate(jc, "my-app")
            output.shouldContain("bin my-app")
        }

        test("renders short-only flags") {
            class App {
                @Parameter(names = ["-v"], description = "Be verbose")
                var verbose = false
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""flag -v help="Be verbose""")
        }

        test("renders long-only flags") {
            class App {
                @Parameter(names = ["--verbose"], description = "Be verbose")
                var verbose = false
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""flag --verbose help="Be verbose""")
        }
    }

    context("nested subcommands") {
        test("renders subcommands recursively") {
            @Parameters(commandNames = ["nested"], commandDescription = "A nested subcommand")
            class Nested

            @Parameters(commandNames = ["sub"], commandDescription = "A subcommand")
            class Sub

            @Parameters(commandNames = ["app"], commandDescription = "An app")
            class App

            val jc = JCommander(App())
            jc.addCommand("sub", Sub())
            val subJc = jc.commands["sub"]!!
            subJc.addCommand("nested", Nested())

            val output = generate(jc)
            output.shouldContain("cmd sub")
            output.shouldContain("cmd nested")
        }
    }

    context("required options") {
        test("marks mandatory options as required") {
            class Deploy {
                @Parameter(names = ["--env"], description = "Target environment", required = true)
                var env: String? = null
            }
            val jc = JCommander(Deploy())
            val output = generate(jc)
            output.shouldContain("""flag --env help="Target environment" required=#true""")
        }
    }

    context("hidden") {
        test("hides commands and options") {
            @Parameters(commandNames = ["internal"], commandDescription = "Internal command", hidden = true)
            class HiddenCmd

            class App {
                @Parameter(names = ["--secret"], description = "Secret flag", hidden = true)
                var secret: String? = null
            }
            val jc = JCommander(App())
            jc.addCommand("internal", HiddenCmd())
            val output = generate(jc)
            output.shouldContain("cmd internal hide=#true")
            output.shouldContain("""flag --secret help="Secret flag" hide=#true""")
        }
    }

    context("argument inference") {
        test("converts main parameter") {
            class Cmd {
                @Parameter(description = "Input file")
                var file: String? = null
            }
            val jc = JCommander(Cmd())
            val output = generate(jc)
            output.shouldContain("arg <FILE>")
        }

        test("converts optional main parameter") {
            class Cmd {
                @Parameter(description = "Optional name", required = false)
                var name: String? = null
            }
            val jc = JCommander(Cmd())
            val output = generate(jc)
            output.shouldContain("""arg "[NAME]""")
            output.shouldContain("required=#false")
        }

        test("converts variadic main parameter") {
            class Cmd {
                @Parameter(description = "Multiple files", variableArity = true)
                var files: List<String> = mutableListOf()
            }
            val jc = JCommander(Cmd())
            val output = generate(jc)
            output.shouldContain("""arg "[FILES]…""")
            output.shouldContain("var=#true")
        }

        test("converts flag with arity 0 as boolean") {
            class App {
                @Parameter(names = ["-c", "--cheese"], description = "Add cheese", arity = 0)
                var cheese = false
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""flag "-c --cheese"""")
        }
    }

    context("default values") {
        test("renders default value for option") {
            class App {
                @Parameter(names = ["--output"], description = "Output format")
                var output = "json"

                @Parameter(names = ["--retries"], description = "Number of retries")
                var retries = 3
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""flag --output help="Output format" default=json""")
            output.shouldContain("""flag --retries help="Number of retries" default="3"""")
        }

        test("skips false default for boolean flags") {
            class App {
                @Parameter(names = ["--force"], description = "Force the operation")
                var force = false
            }
            val jc = JCommander(App())
            val output = generate(jc)
            val forceLine = output.split("\n").find { it.contains("flag --force") }
            forceLine.shouldNotBeNull()
            forceLine.shouldNotContain("default")
        }

        test("preserves true default for boolean flags") {
            class App {
                @Parameter(names = ["--color"], description = "Enable color")
                var color = true
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""flag --color help="Enable color"""")
            // JCommander exposes field initialization value as default
            val colorLine = output.split("\n").find { it.contains("flag --color") }
            colorLine.shouldNotBeNull()
            colorLine.shouldContain("defaultBool=#true")
        }

        test("preserves string zero as default") {
            class App {
                @Parameter(names = ["--port"], description = "Port number")
                var port = "0"
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldContain("""default="0"""")
        }
    }

    context("boolean flags") {
        test("does not render arg for boolean flags") {
            class App {
                @Parameter(names = ["--force"], description = "Force the operation")
                var force = false
            }
            val jc = JCommander(App())
            val output = generate(jc)
            val forceLine = output.split("\n").find { it.contains("flag --force") }
            forceLine.shouldNotBeNull()
            forceLine.shouldNotContain("arg")
        }
    }

    context("skips builtin") {
        test("does not render --help flag") {
            class App {
                @Parameter(names = ["--custom"], description = "A custom flag")
                var custom: String? = null
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldNotContain("flag --help")
            output.shouldContain("flag --custom")
        }

        test("does not render --version flag") {
            class App {
                @Parameter(names = ["--version"], description = "Show version", help = true)
                var version = false

                @Parameter(names = ["--custom"], description = "A custom flag")
                var custom: String? = null
            }
            val jc = JCommander(App())
            val output = generate(jc)
            output.shouldNotContain("flag --version")
            output.shouldContain("flag --custom")
        }
    }

    context("subcommand_required") {
        test("sets subcommand_required for commands with subcommands and no args") {
            class Config

            val jc = JCommander(Config())
            val configJc = JCommander(Config())
            configJc.addCommand("get", Any())
            configJc.addCommand("set", Any())
            jc.addCommand("config", configJc)

            val output = generate(jc)
            output.shouldContain("subcommand_required=#true")
        }

        test("does not set subcommand_required when command has positional args") {
            class Greet {
                @Parameter(description = "Name to greet")
                var name: String? = null
            }

            class Formally

            val jc = JCommander(Greet())
            jc.addCommand("formally", Formally())

            val output = generate(jc)
            val greetLine = output.split("\n").find { it.contains("cmd greet") }
            greetLine.shouldNotBeNull()
            greetLine.shouldNotContain("subcommand_required")
        }
    }

    context("JSON output") {
        test("generates valid JSON") {
            class MyCli {
                @Parameter(names = ["-v", "--verbose"], description = "Enable verbose output")
                var verbose = false
            }
            val jc = JCommander(MyCli())
            jc.programName = "mycli"
            val output = generateJSON(jc)
            shouldNotThrowAny { validateKDL(output) }
            output.shouldContain(""""name": "mycli"""")
            output.shouldContain(""""bin": "mycli"""")
        }
    }
})
