package clikt_usage

import com.github.ajalt.clikt.completion.CompletionCandidates
import com.github.ajalt.clikt.core.CliktCommand
import com.github.ajalt.clikt.core.NoOpCliktCommand
import com.github.ajalt.clikt.core.subcommands
import com.github.ajalt.clikt.parameters.arguments.argument
import com.github.ajalt.clikt.parameters.arguments.multiple
import com.github.ajalt.clikt.parameters.arguments.optional
import com.github.ajalt.clikt.parameters.options.default
import com.github.ajalt.clikt.parameters.options.flag
import com.github.ajalt.clikt.parameters.options.option
import com.github.ajalt.clikt.parameters.options.required
import io.kotest.assertions.throwables.shouldNotThrowAny
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.booleans.shouldBeFalse
import io.kotest.matchers.booleans.shouldBeTrue
import io.kotest.matchers.shouldBe
import io.kotest.matchers.shouldNotBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain
import usage_spec.validateKDL

class CliktUsageTest : FunSpec({

    context("simple command") {
        test("generates spec for a basic CLI with options") {
            class MyCli : CliktCommand(name = "mycli") {
                val verbose by option("-v", "--verbose", help = "Enable verbose output")
                val config by option("-c", "--config", help = "Config file path")
                override fun run() = Unit
            }

            val output = generate(MyCli())

            output shouldContain "name mycli"
            output shouldContain "bin mycli"
            output shouldContain """flag "-v --verbose" help="Enable verbose output"""
            output shouldContain """flag "-c --config" help="Config file path"""
        }

        test("includes generated comment header") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }
            val output = generate(App())
            output shouldContain "// @generated by clikt-usage from Clikt metadata"
        }

        test("uses custom bin name when provided") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }
            val output = generate(App(), "my-app")
            output shouldContain "bin my-app"
        }

        test("renders short-only flags") {
            class App : CliktCommand(name = "app") {
                val verbose by option("-v", help = "Be verbose")
                override fun run() = Unit
            }
            val output = generate(App())
            output shouldContain """flag -v help="Be verbose"""
        }

        test("renders long-only flags") {
            class App : CliktCommand(name = "app") {
                val verbose by option("--verbose", help = "Be verbose")
                override fun run() = Unit
            }
            val output = generate(App())
            output shouldContain """flag --verbose help="Be verbose"""
        }
    }

    context("nested subcommands") {
        test("renders subcommands recursively") {
            class Nested : CliktCommand(name = "nested") {
                override fun run() = Unit
            }
            class Sub : CliktCommand(name = "sub") {
                init { subcommands(Nested()) }
                override fun run() = Unit
            }
            class Root : CliktCommand(name = "app") {
                init { subcommands(Sub()) }
                override fun run() = Unit
            }

            val output = generate(Root())

            output shouldContain "cmd sub"
            output shouldContain "cmd nested"
        }
    }

    context("global/persistent flags") {
        test("does not mark root-level flags as global") {
            class Run : CliktCommand(name = "run") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Run()) }
                val debug by option("-d", "--debug", help = "Enable debug mode")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag "-d --debug" help="Enable debug mode"""
        }
    }

    context("required options") {
        test("marks mandatory options as required") {
            class Deploy : CliktCommand(name = "deploy") {
                val env by option("--env", help = "Target environment").required()
                override fun run() = Unit
            }

            val output = generate(Deploy())

            output shouldContain """flag --env help="Target environment" required=#true"""
        }
    }

    context("hidden and deprecated") {
        test("hides commands and options") {
            class HiddenCmd : CliktCommand(name = "internal") {
                override val hiddenFromHelp get() = true
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(HiddenCmd()) }
                val secret by option("--secret", help = "Secret flag", hidden = true)
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd internal hide=#true"
            output shouldContain """flag --secret help="Secret flag" hide=#true"""
        }
    }

    context("argument inference") {
        test("converts required arguments") {
            class Cmd : CliktCommand(name = "cmd") {
                val file by argument(name = "file", help = "Input file")
                override fun run() = Unit
            }

            val output = generate(Cmd())

            output shouldContain "arg <file>"
        }

        test("converts optional arguments") {
            class Cmd : CliktCommand(name = "cmd") {
                val name by argument(name = "name", help = "Optional name").optional()
                override fun run() = Unit
            }

            val output = generate(Cmd())

            output shouldContain """arg "[name]"""
            output shouldContain "required=#false"
        }

        test("converts variadic arguments") {
            class Cmd : CliktCommand(name = "cmd") {
                val files by argument(name = "files", help = "Multiple files").multiple()
                override fun run() = Unit
            }

            val output = generate(Cmd())

            output shouldContain "arg \"[files]\u2026\""
            output shouldContain "var=#true"
        }

        test("converts mixed required and optional args") {
            class Cmd : CliktCommand(name = "cmd") {
                val source by argument(name = "source", help = "Source path")
                val dest by argument(name = "dest", help = "Destination path").optional()
                override fun run() = Unit
            }

            val output = generate(Cmd())

            output shouldContain "arg <source>"
            output shouldContain """arg "[dest]"""
            output shouldContain "required=#false"
        }

        test("renders flag with optional argument") {
            class App : CliktCommand(name = "app") {
                val cheese by option("-c", "--cheese", help = "Add cheese")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag "-c --cheese"""
        }
    }

    context("choices") {
        test("renders choices for option arguments") {
            class Deploy : CliktCommand(name = "deploy") {
                val format by option(
                    "--format", help = "Output format",
                    completionCandidates = CompletionCandidates.Fixed(setOf("json", "yaml", "toml"))
                )
                override fun run() = Unit
            }

            val output = generate(Deploy())

            output shouldContain "choices"
            output shouldContain "json"
            output shouldContain "yaml"
            output shouldContain "toml"
        }

        test("renders choices for positional arguments") {
            class Deploy : CliktCommand(name = "deploy") {
                val env by argument(
                    name = "env", help = "Environment",
                    completionCandidates = CompletionCandidates.Fixed(setOf("dev", "staging", "prod"))
                )
                override fun run() = Unit
            }

            val output = generate(Deploy())

            output shouldContain "arg <env>"
            output shouldContain "choices"
            output shouldContain "dev"
            output shouldContain "staging"
            output shouldContain "prod"
        }
    }

    context("default values") {
        test("renders default value for option") {
            class App : CliktCommand(name = "app") {
                val output by option("--output", help = "Output format").default("json")
                val retries by option("--retries", help = "Number of retries").default("3")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag --output help="Output format" default=json"""
            output shouldContain """flag --retries help="Number of retries" default="3""""
        }

        test("renders default value for argument") {
            class App : CliktCommand(name = "app") {
                val file by argument(name = "file", help = "Input file").optional()
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """arg "[file]"""
        }

        test("skips false default for boolean flags") {
            class App : CliktCommand(name = "app") {
                val force by option("--force", help = "Force the operation").flag()
                override fun run() = Unit
            }

            val output = generate(App())

            val forceLine = output.split("\n").find { it.contains("flag --force") }
            forceLine shouldNotBe null
            forceLine shouldNotContain "default"
        }

        test("preserves string zero as default") {
            class App : CliktCommand(name = "app") {
                val port by option("--port", help = "Port number").default("0")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """default="0""""
        }

        test("preserves true default for boolean flags") {
            class App : CliktCommand(name = "app") {
                val color by option("--color", help = "Enable color").flag(default = true)
                override fun run() = Unit
            }

            val output = generate(App())

            // Clikt 5 does not expose default=true via metadata; just verify help is present
            output shouldContain """flag --color help="Enable color""""
        }
    }

    context("boolean flags") {
        test("does not render arg for boolean flags") {
            class App : CliktCommand(name = "app") {
                val force by option("--force", help = "Force the operation").flag()
                override fun run() = Unit
            }

            val output = generate(App())

            val forceLine = output.split("\n").find { it.contains("flag --force") }
            forceLine shouldNotBe null
            forceLine shouldNotContain "arg"
        }
    }

    context("skips builtin") {
        test("does not render the help subcommand") {
            class Run : CliktCommand(name = "run") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Run()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd run"
        }

        test("does not render --help flag") {
            class App : CliktCommand(name = "app") {
                val custom by option("--custom", help = "A custom flag")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldNotContain "flag --help"
            output shouldContain "flag --custom"
        }
    }

    context("subcommand_required") {
        test("sets subcommand_required for non-runnable commands with subcommands") {
            class Get : CliktCommand(name = "get") {
                override fun run() = Unit
            }
            class Set : CliktCommand(name = "set") {
                override fun run() = Unit
            }
            class Config : NoOpCliktCommand(name = "config") {
                init { subcommands(Get(), Set()) }
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Config()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "subcommand_required=#true"
        }

        test("does not set subcommand_required for runnable commands") {
            class List : CliktCommand(name = "list") {
                override fun run() = Unit
            }
            class Task : CliktCommand(name = "task") {
                init { subcommands(List()) }
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Task()) }
                override fun run() = Unit
            }

            val output = generate(App())

            val taskLine = output.split("\n").find { it.contains("cmd task") }
            taskLine shouldNotBe null
            taskLine shouldNotContain "subcommand_required"
        }

        test("does not set subcommand_required when command has positional args") {
            class Formally : CliktCommand(name = "formally") {
                override fun run() = Unit
            }
            class Greet : CliktCommand(name = "greet") {
                init { subcommands(Formally()) }
                val name by argument(name = "name", help = "Name to greet")
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Greet()) }
                override fun run() = Unit
            }

            val output = generate(App())

            val greetLine = output.split("\n").find { it.contains("cmd greet") }
            greetLine shouldNotBe null
            greetLine shouldNotContain "subcommand_required"
        }
    }

    context("aliases") {
        test("renders command aliases") {
            class Install : CliktCommand(name = "install") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Install()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd install"
            output shouldNotContain "alias"
        }

        test("renders single alias") {
            class Remove : CliktCommand(name = "remove") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Remove()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd remove"
        }
    }

    context("long help") {
        test("renders about for root command") {
            val output = generate(object : CliktCommand(name = "app") {
                override fun run() = Unit
            })

            output shouldContain "name app"
            output shouldContain "bin app"
        }

        test("uses about field when present") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "name app"
            output shouldContain "bin app"
        }

        test("renders help for subcommand") {
            class Sub : CliktCommand(name = "sub") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Sub()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd sub"
        }
    }

    context("negated options") {
        test("renders negate for --no- options") {
            class App : CliktCommand(name = "app") {
                val color by option("--color", "--no-color", help = "Enable/disable color").flag()
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "negate=--color"
        }

        test("negated boolean options do not have arg") {
            class App : CliktCommand(name = "app") {
                val color by option("--color", "--no-color", help = "Enable/disable color").flag()
                override fun run() = Unit
            }

            val spec = convertRoot(App())
            val colorFlag = spec.flags.find { it.long == "color" }
            colorFlag shouldNotBe null
            colorFlag!!.negate shouldBe "--color"
            colorFlag.arg shouldBe null
        }
    }

    context("environment variables") {
        test("renders env for options with env vars") {
            class App : CliktCommand(name = "app") {
                val color by option("--color", help = "Color output", envvar = "MYCLI_COLOR")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "env=MYCLI_COLOR"
        }
    }

    context("special character escaping") {
        test("handles newlines in command help") {
            class Sub : CliktCommand(name = "sub") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Sub()) }
                override fun run() = Unit
            }

            val output = generate(App())
            val kdlContent = output.split("\n").drop(1).joinToString("\n")

            shouldNotThrowAny {
                validateKDL(kdlContent)
            }
        }

        test("handles special chars in flag help") {
            class App : CliktCommand(name = "app") {
                val format by option("--format", help = "Output format")
                override fun run() = Unit
            }

            val output = generate(App())
            val kdlContent = output.split("\n").drop(1).joinToString("\n")

            shouldNotThrowAny {
                validateKDL(kdlContent)
            }
        }
    }

    context("KDL round-trip validation") {
        test("generates valid KDL for basic command") {
            class App : CliktCommand(name = "app") {
                val verbose by option("-v", "--verbose", help = "Be verbose")
                val file by option("-f", "--file", help = "Input file")
                override fun run() = Unit
            }

            val output = generate(App())
            val kdlContent = output.split("\n").drop(1).joinToString("\n")

            shouldNotThrowAny {
                validateKDL(kdlContent)
            }
        }

        test("generates valid KDL for nested commands") {
            class Get : CliktCommand(name = "get") {
                override fun run() = Unit
            }
            class Config : CliktCommand(name = "config") {
                init { subcommands(Get()) }
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Config()) }
                override fun run() = Unit
            }

            val output = generate(App())
            val kdlContent = output.split("\n").drop(1).joinToString("\n")

            shouldNotThrowAny {
                validateKDL(kdlContent)
            }
        }
    }

    context("generateKDL and JSON output") {
        test("generateKDL is an alias for generate") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }
            generateKDL(App()) shouldBe generate(App())
        }

        test("generates JSON output with correct structure") {
            class Run : CliktCommand(name = "run") {
                override fun run() = Unit
            }
            class MyCli : CliktCommand(name = "mycli") {
                init { subcommands(Run()) }
                val verbose by option("--verbose", help = "Be verbose")
                override fun run() = Unit
            }

            val json = generateJSON(MyCli())

            json shouldContain "mycli"
            json shouldContain "verbose"
            json shouldContain "run"
        }

        test("includes choices in JSON output") {
            class Deploy : CliktCommand(name = "deploy") {
                val env by argument(
                    name = "env", help = "Environment",
                    completionCandidates = CompletionCandidates.Fixed(setOf("dev", "prod"))
                )
                override fun run() = Unit
            }

            val json = generateJSON(Deploy())
            json shouldContain "dev"
            json shouldContain "prod"
        }

        test("includes flag details in JSON") {
            class App : CliktCommand(name = "app") {
                val env by option("--env", help = "Target environment").required()
                val noColor by option("--color", "--no-color", help = "Disable color").flag()
                override fun run() = Unit
            }

            val json = generateJSON(App())
            json shouldContain "required"
            json shouldContain "negate"
            json shouldContain "--color"
        }

        test("handles custom bin name in JSON") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }
            val json = generateJSON(App(), "my-tool")
            json shouldContain "my-tool"
        }
    }

    context("convertRoot") {
        test("returns a spec with correct structure") {
            class MyCli : CliktCommand(name = "mycli") {
                val verbose by option("--verbose", help = "Be verbose")
                override fun run() = Unit
            }

            val spec = convertRoot(MyCli())

            spec.name shouldBe "mycli"
            spec.bin shouldBe "mycli"
            spec.version shouldBe ""
            spec.about shouldBe ""
            spec.flags.size shouldBe 1
            spec.flags[0].long shouldBe "verbose"
        }

        test("includes arguments in spec") {
            class Cmd : CliktCommand(name = "cmd") {
                val file by argument(name = "file", help = "Input file")
                val output by argument(name = "output", help = "Output file").optional()
                override fun run() = Unit
            }

            val spec = convertRoot(Cmd())

            spec.args.size shouldBe 2
            spec.args[0].name shouldBe "file"
            spec.args[0].required.shouldBeTrue()
            spec.args[1].name shouldBe "output"
            spec.args[1].required.shouldBeFalse()
        }
    }

    context("edge cases") {
        test("handles empty command with no options or args") {
            class Empty : CliktCommand(name = "empty") {
                override fun run() = Unit
            }
            val output = generate(Empty())

            output shouldContain "name empty"
            output shouldContain "bin empty"
            output shouldNotContain "flag"
            output shouldNotContain "arg"
            output shouldNotContain "cmd"
        }

        test("handles command with only subcommands") {
            class Start : CliktCommand(name = "start") {
                override fun run() = Unit
            }
            class Stop : CliktCommand(name = "stop") {
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Start(), Stop()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain "cmd start"
            output shouldContain "cmd stop"
        }

        test("handles option with required") {
            class App : CliktCommand(name = "app") {
                val token by option("--token", help = "Auth token").required()
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag --token help="Auth token" required=#true"""
        }

        test("handles variadic option argument") {
            class App : CliktCommand(name = "app") {
                val include by option("--include", help = "Include patterns")
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag --include help="Include patterns""""
        }

        test("skips version field when not set") {
            class App : CliktCommand(name = "app") {
                override fun run() = Unit
            }
            val output = generate(App())

            output shouldNotContain "version "
        }

        test("handles multiple flags on subcommand") {
            class Build : CliktCommand(name = "build") {
                val output by option("-o", "--output", help = "Output directory")
                val minify by option("--minify", help = "Minify output").flag()
                val watch by option("--watch", help = "Watch for changes").flag()
                override fun run() = Unit
            }
            class App : CliktCommand(name = "app") {
                init { subcommands(Build()) }
                override fun run() = Unit
            }

            val output = generate(App())

            output shouldContain """flag "-o --output" help="Output directory"""
            output shouldContain """flag --minify help="Minify output"""
            output shouldContain """flag --watch help="Watch for changes"""
        }
    }
})
