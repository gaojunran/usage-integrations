package clikt_usage

import com.github.ajalt.clikt.core.CliktCommand
import usage_spec.generate

fun generate(cmd: CliktCommand, binName: String? = null): String {
    val spec = convertRoot(cmd, binName)
    return generate(spec, format = "kdl", comment = "@generated by clikt-usage from Clikt metadata")
}

fun generateKDL(cmd: CliktCommand, binName: String? = null): String {
    return generate(cmd, binName)
}

fun generateJSON(cmd: CliktCommand, binName: String? = null): String {
    val spec = convertRoot(cmd, binName)
    return generate(spec, format = "json")
}
