describe("convertRoot", () => {
  it("returns a spec with correct structure", () => {
    const cmd = new Command("mycli")
      .version("2.0.0")
      .description("A CLI tool")
      .option("--verbose", "Be verbose");

    const spec = convertRoot(cmd);

    expect(spec.name).toBe("mycli");
    expect(spec.bin).toBe("mycli");
    expect(spec.version).toBe("2.0.0");
    expect(spec.about).toBe("A CLI tool");
    expect(spec.flags).toHaveLength(1);
    expect(spec.flags[0].long).toBe("verbose");
  });

  it("includes arguments in spec", () => {
    const cmd = new Command("cmd")
      .argument("<file>", "Input file")
      .argument("[output]", "Output file");

    const spec = convertRoot(cmd);

    expect(spec.args).toHaveLength(2);
    expect(spec.args[0].name).toBe("file");
    expect(spec.args[0].required).toBe(true);
    expect(spec.args[1].name).toBe("output");
    expect(spec.args[1].required).toBe(false);
  });
});

