describe("full output format", () => {
  it("matches expected KDL output for a complete example", () => {
    const cmd = new Command("example")
      .version("1.0.0")
      .description("An example CLI")
      .option("-f, --file <FILE>", "Some input file")
      .option("--verbose", "Enable verbose output");

    const output = generate(cmd, "example");

    expect(output).toContain("name example");
    expect(output).toContain("bin example");
    expect(output).toContain(`version "1.0.0"`);
    expect(output).toContain(`about "An example CLI"`);
    expect(output).toContain(`flag "-f --file" help="Some input file"`);
    expect(output).toContain(`flag --verbose help="Enable verbose output"`);
  });

  it("generates complete KDL output matching clap_usage snapshot style", () => {
    const cmd = new Command("example")
      .option("-f, --file <FILE>", "some input file")
      .option("--usage");

    const output = generate(cmd, "example");

    // Should match the style of clap_usage snapshot:
    // name example
    // bin example
    // flag "-f --file" help="some input file" {
    //     arg <FILE>
    // }
    // flag --usage
    const lines = output.split("\n").filter((l) => !l.startsWith("//"));
    expect(lines).toContain("name example");
    expect(lines).toContain("bin example");
    expect(lines.some((l) => l.includes(`flag "-f --file" help="some input file"`))).toBe(true);
    expect(lines).toContain("flag --usage");
  });

  it("renders deeply nested command structure", () => {
    const root = new Command("myapp").version("1.0.0").description("My application");
    const db = new Command("db").description("Database operations");
    const migrate = new Command("migrate").description("Run migrations");
    const up = new Command("up").description("Apply migrations");
    const down = new Command("down").description("Rollback migrations");

    migrate.addCommand(up);
    migrate.addCommand(down);
    db.addCommand(migrate);
    root.addCommand(db);

    const output = generate(root);

    expect(output).toContain("cmd db");
    expect(output).toContain("help=\"Database operations\"");
    expect(output).toContain("cmd migrate");
    expect(output).toContain("help=\"Run migrations\"");
    expect(output).toContain("cmd up help=\"Apply migrations\"");
    expect(output).toContain("cmd down help=\"Rollback migrations\"");
  });
});

describe("JSON output", () => {
  it("generates JSON output with correct structure", () => {
    const cmd = new Command("mycli")
      .version("2.0.0")
      .description("A CLI tool")
      .option("--verbose", "Be verbose");
    const sub = new Command("run").description("Run something");
    cmd.addCommand(sub);

    const json = generateJSON(cmd);
    const parsed = JSON.parse(json);

    expect(parsed.name).toBe("mycli");
    expect(parsed.version).toBe("2.0.0");
    expect(parsed.about).toBe("A CLI tool");
    expect(parsed.flags).toHaveLength(1);
    expect(parsed.cmds).toHaveLength(1);
    expect(parsed.cmds[0].name).toBe("run");
  });

  it("includes choices in JSON output", () => {
    const cmd = new Command("deploy").addArgument(
      new Argument("<env>", "Environment").choices(["dev", "prod"])
    );

    const json = generateJSON(cmd);
    const parsed = JSON.parse(json);

    expect(parsed.args[0].choices).toEqual(["dev", "prod"]);
  });

  it("includes flag details in JSON", () => {
    const cmd = new Command("app")
      .requiredOption("--env <ENV>", "Target environment")
      .option("--no-color", "Disable color");

    const json = generateJSON(cmd);
    const parsed = JSON.parse(json);

    expect(parsed.flags).toHaveLength(2);
    const envFlag = parsed.flags.find((f: { name: string }) => f.name === "--env");
    expect(envFlag.required).toBe(true);
    expect(envFlag.arg.name).toBe("ENV");

    const colorFlag = parsed.flags.find((f: { name: string }) => f.name === "--no-color");
    expect(colorFlag.negate).toBe("--color");
  });

  it("handles custom bin name in JSON", () => {
    const cmd = new Command("app").description("A tool");
    const json = generateJSON(cmd, "my-tool");
    const parsed = JSON.parse(json);

    expect(parsed.bin).toBe("my-tool");
  });
});

describe("edge cases", () => {
  it("handles empty command with no options or args", () => {
    const cmd = new Command("empty");
    const output = generate(cmd);

    expect(output).toContain("name empty");
    expect(output).toContain("bin empty");
    expect(output).not.toContain("flag");
    expect(output).not.toContain("arg");
    expect(output).not.toContain("cmd");
  });

  it("handles command with only subcommands", () => {
    const root = new Command("app");
    root.addCommand(new Command("start").description("Start"));
    root.addCommand(new Command("stop").description("Stop"));

    const output = generate(root);

    expect(output).toContain("cmd start");
    expect(output).toContain("cmd stop");
  });

  it("handles option with makeOptionMandatory", () => {
    const cmd = new Command("app").addOption(
      new Option("--token <TOKEN>", "Auth token").makeOptionMandatory()
    );

    const output = generate(cmd);

    expect(output).toContain(`flag --token help="Auth token" required=#true`);
  });

  it("handles variadic option argument", () => {
    const cmd = new Command("app").option("--include <PATTERNS...>", "Include patterns");

    const spec = convertRoot(cmd);
    const includeFlag = spec.flags.find((f) => f.long === "include");

    expect(includeFlag?.var).toBe(true);
    expect(includeFlag?.arg?.var).toBe(true);
  });

  it("skips version field when not set", () => {
    const cmd = new Command("app").description("A tool");
    const output = generate(cmd);

    // Should not have a version line (only name, bin, about)
    expect(output).not.toContain("version ");
  });

  it("handles multiple flags on subcommand", () => {
    const root = new Command("app");
    const sub = new Command("build")
      .description("Build the project")
      .option("-o, --output <DIR>", "Output directory")
      .option("--minify", "Minify output")
      .option("--watch", "Watch for changes");
    root.addCommand(sub);

    const output = generate(root);

    expect(output).toContain(`flag "-o --output" help="Output directory"`);
    expect(output).toContain(`flag --minify help="Minify output"`);
    expect(output).toContain(`flag --watch help="Watch for changes"`);
  });
});
