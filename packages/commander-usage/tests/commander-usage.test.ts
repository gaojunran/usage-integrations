describe("default values", () => {
  it("renders default value for option", () => {
    const cmd = new Command("app")
      .option("--output <FORMAT>", "Output format", "json")
      .option("--retries <N>", "Number of retries", "3");

    const output = generate(cmd);

    expect(output).toContain(`flag --output help="Output format" default=json`);
    expect(output).toContain(`flag --retries help="Number of retries" default="3"`);
  });

  it("renders default value for argument", () => {
    const cmd = new Command("app").argument("[file]", "Input file", "input.txt");

    const output = generate(cmd);

    expect(output).toContain("default=input.txt");
  });

  it("skips false default for boolean flags", () => {
    const cmd = new Command("app").option("--force", "Force the operation", false);

    const output = generate(cmd);

    const forceLine = output.split("\n").find((l) => l.includes("flag --force"));
    expect(forceLine).toBeDefined();
    expect(forceLine).not.toContain("default");
  });

  it("preserves string zero as default", () => {
    const cmd = new Command("app").option("--port <PORT>", "Port number", "0");

    const output = generate(cmd);

    expect(output).toContain(`default="0"`);
  });

  it("preserves true default for boolean flags", () => {
    const cmd = new Command("app").addOption(
      new Option("--color", "Enable color").default(true)
    );

    const output = generate(cmd);

    expect(output).toContain(`flag --color help="Enable color" default=#true`);
  });
});

