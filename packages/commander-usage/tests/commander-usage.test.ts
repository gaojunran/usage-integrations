describe("hidden and deprecated", () => {
  it("hides commands and options", () => {
    const root = new Command("app");
    const hiddenCmd = new Command("internal").description("Internal command");
    hiddenCmd._hidden = true;
    root.addCommand(hiddenCmd);

    const opt = new Option("--secret <VAL>", "Secret flag");
    opt.hideHelp();
    root.addOption(opt);

    const output = generate(root);

    expect(output).toContain("cmd internal hide=#true");
    expect(output).toContain(`flag --secret help="Secret flag" hide=#true`);
  });
});

describe("argument inference", () => {
  it("converts required arguments", () => {
    const cmd = new Command("cmd").argument("<file>", "Input file");

    const output = generate(cmd);

    expect(output).toContain("arg <file>");
    expect(output).toContain(`help="Input file"`);
  });

  it("converts optional arguments", () => {
    const cmd = new Command("cmd").argument("[name]", "Optional name");

    const output = generate(cmd);

    expect(output).toContain(`arg "[name]"`);
    expect(output).toContain("required=#false");
  });

  it("converts variadic arguments", () => {
    const cmd = new Command("cmd").argument("<files...>", "Multiple files");

    const output = generate(cmd);

    expect(output).toContain("arg <files>\u2026");
    expect(output).toContain("var=#true");
  });

  it("converts mixed required and optional args", () => {
    const cmd = new Command("cmd")
      .argument("<source>", "Source path")
      .argument("[dest]", "Destination path");

    const output = generate(cmd);

    expect(output).toContain("arg <source>");
    expect(output).toContain(`arg "[dest]"`);
    expect(output).toContain("required=#false");
  });
});

