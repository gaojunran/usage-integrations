describe("subcommand_required", () => {
  it("sets subcommand_required for non-runnable commands with subcommands", () => {
    const root = new Command("app");
    const sub = new Command("config").description("Manage config");
    sub.addCommand(new Command("get").description("Get a value"));
    sub.addCommand(new Command("set").description("Set a value"));
    root.addCommand(sub);

    const output = generate(root);

    expect(output).toContain("subcommand_required=#true");
  });

  it("does not set subcommand_required for runnable commands", () => {
    const root = new Command("app");
    const sub = new Command("task").description("Run a task").action(() => {});
    sub.addCommand(new Command("list").description("List tasks"));
    root.addCommand(sub);

    const output = generate(root);

    const taskLine = output.split("\n").find((l) => l.includes("cmd task"));
    expect(taskLine).toBeDefined();
    expect(taskLine).not.toContain("subcommand_required");
  });

  it("does not set subcommand_required when command has positional args", () => {
    const root = new Command("app");
    const sub = new Command("greet").argument("<name>", "Name to greet");
    sub.addCommand(new Command("formally").description("Formal greeting"));
    root.addCommand(sub);

    const output = generate(root);

    const greetLine = output.split("\n").find((l) => l.includes("cmd greet"));
    expect(greetLine).toBeDefined();
    expect(greetLine).not.toContain("subcommand_required");
  });
});

