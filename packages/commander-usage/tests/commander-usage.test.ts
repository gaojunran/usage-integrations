describe("negated options", () => {
  it("renders negate for --no- options", () => {
    const cmd = new Command("app").option("--no-color", "Disable color output");

    const output = generate(cmd);

    expect(output).toContain("negate=--color");
  });

  it("negated boolean options do not have arg", () => {
    const cmd = new Command("app").option("--no-color", "Disable color output");

    const spec = convertRoot(cmd);
    const colorFlag = spec.flags.find((f) => f.long === "no-color");
    expect(colorFlag).toBeDefined();
    expect(colorFlag!.negate).toBe("--color");
    // --no-color is boolean (no arg), negate flag
    expect(colorFlag!.arg).toBeNull();
  });
});

