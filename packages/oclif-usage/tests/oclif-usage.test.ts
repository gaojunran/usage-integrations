describe("edge cases", () => {
  it("handles empty CLI with no options or args", () => {
    const config = makeConfig({ bin: "empty" });
    const output = generate(config);

    expect(output).toContain("name empty");
    expect(output).toContain("bin empty");
    expect(output).not.toMatch(/\bflag\b/);
    expect(output).not.toMatch(/^(\s*)arg /m);
    expect(output).not.toMatch(/\bcmd\b/);
  });

  it("handles CLI with only subcommands", () => {
    const config = makeConfig({
      bin: "app",
      commands: [
        { id: "start", flags: {}, args: {}, description: "Start" },
        { id: "stop", flags: {}, args: {}, description: "Stop" },
      ],
    });

    const output = generate(config);

    expect(output).toContain("cmd start");
    expect(output).toContain("cmd stop");
  });

  it("handles deeply nested command structure", () => {
    const config = makeConfig({
      bin: "myapp",
      version: "1.0.0",
      commands: [
        { id: "db:migrate:up", flags: {}, args: {}, description: "Apply migrations" },
        { id: "db:migrate:down", flags: {}, args: {}, description: "Rollback migrations" },
      ],
      topics: [
        { name: "db", description: "Database operations" },
        { name: "db:migrate", description: "Run migrations" },
      ],
    });

    const output = generate(config);

    expect(output).toContain("cmd db");
    expect(output).toContain("Database operations");
    expect(output).toContain("cmd migrate");
    expect(output).toContain("migrate");
  });

  it("excludes root command from subcommand tree", () => {
    const config = makeConfig({
      bin: "mycli",
      commands: [
        {
          id: "mycli",
          flags: { verbose: { name: "verbose", type: "boolean", description: "Be verbose" } },
          args: {},
          description: "The CLI itself",
        },
        { id: "run", flags: {}, args: {}, description: "Run something" },
      ],
    });

    const spec = convertRoot(config);

    // Root command flags should be at top level
    expect(spec.flags).toHaveLength(1);
    expect(spec.flags[0].long).toBe("verbose");
    // Only "run" should appear as a subcommand, not "mycli"
    expect(spec.cmds).toHaveLength(1);
    expect(spec.cmds[0].name).toBe("run");
  });
});

