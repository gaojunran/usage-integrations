import { describe, it, expect } from "vitest";
import { generate, generateKDL, generateJSON, convertRoot } from "../src/index.js";
import type { OclifConfig, OclifCommand } from "../src/index.js";
import { validateKDL } from "@usage-spec/core";

function makeConfig(partial: Partial<OclifConfig> & { bin: string }): OclifConfig {
  return {
    version: "1.0.0",
    commands: [],
    topics: [],
    ...partial,
  };
}

describe("simple command", () => {
  it("generates spec for a basic CLI", () => {
    const config = makeConfig({
      bin: "mycli",
      commands: [
        {
          id: "mycli",
          flags: {
            verbose: { name: "verbose", type: "boolean", description: "Enable verbose output", char: "v" },
            config: { name: "config", type: "option", description: "Config file path", char: "c", helpValue: "<PATH>" },
          },
          args: {},
        },
      ],
    });

    const output = generate(config);

    expect(output).toContain("name mycli");
    expect(output).toContain("bin mycli");
    expect(output).toContain("version");
    expect(output).toContain("verbose");
    expect(output).toContain("config");
  });

  it("includes generated comment header", () => {
    const config = makeConfig({ bin: "app" });
    const output = generate(config);
    expect(output).toContain("// @generated by @usage-spec/oclif from oclif metadata");
  });
});

